// Cookie-based session issuance for browser callers, alongside (not instead of) the Bearer flow
// in auth.go. Two cookies set together, both Path=/: the session cookie (the JWT itself,
// HttpOnly) and the CSRF cookie (a random value, deliberately NOT HttpOnly — the double-submit
// pattern auth.go enforces on any state-changing cookie-authenticated request relies on
// same-origin JS being the only thing that *can* read it to echo it back).
package httpserver

import (
	"net/http"
	"strconv"

	"github.com/metap-org/metap-go/runtime"
)

const sessionStartedAtCookieName = "metap_session_started_at"

// baseCookie: SameSite=Lax rather than Strict — Strict withholds the cookie even on a plain
// top-level navigation into the app from an external link, which would silently look like "not
// logged in" instead of an actual security boundary.
func baseCookie(name, value string, httpOnly, secure bool, maxAgeSeconds int) *http.Cookie {
	return &http.Cookie{
		Name: name, Value: value, Path: "/", SameSite: http.SameSiteLaxMode,
		Secure: secure, HttpOnly: httpOnly, MaxAge: maxAgeSeconds,
	}
}

// sessionCookies builds the pair of Set-Cookie values a successful login issues. csrfValue is
// generated by the caller (a fresh random value per login) rather than derived from the JWT, so
// a leaked JWT alone still isn't enough to forge the CSRF header.
func sessionCookies(token, csrfValue string, ttlSeconds int, secure bool) (*http.Cookie, *http.Cookie) {
	session := baseCookie(runtime.SessionCookieName, token, true, secure, ttlSeconds)
	csrf := baseCookie(runtime.CSRFCookieName, csrfValue, false, secure, ttlSeconds)
	return session, csrf
}

// sessionStartedAtCookie is set once at login, alongside sessionCookies' pair — **never
// rewritten** after that, which is the whole mechanism: this cookie's own MaxAge equals
// absoluteMaxSeconds *as measured from the original login*, so the browser drops it on its own
// once that absolute cap elapses.
func sessionStartedAtCookie(startedAtUnixSecs, absoluteMaxSeconds int64, secure bool) *http.Cookie {
	return baseCookie(sessionStartedAtCookieName, strconv.FormatInt(startedAtUnixSecs, 10), true, secure, int(absoluteMaxSeconds))
}

// clearSessionCookies is POST /auth/logout's triple — MaxAge(-1) (immediate expiry) with every
// attribute matching what the cookie was originally set with, or the browser treats this as a
// different cookie and the original persists.
func clearSessionCookies(secure bool) (*http.Cookie, *http.Cookie, *http.Cookie) {
	session := baseCookie(runtime.SessionCookieName, "", true, secure, -1)
	csrf := baseCookie(runtime.CSRFCookieName, "", false, secure, -1)
	startedAt := baseCookie(sessionStartedAtCookieName, "", true, secure, -1)
	return session, csrf, startedAt
}

// credentialIssuingRequestAllowed: GET /auth/token's extra gate — mints a fresh Bearer JWT
// carrying the caller's full identity, a different kind of risk than the safe-method rule was
// ever about, so it is CSRF-gated despite being a GET. Mirrors auth.go's own precedence exactly:
// an Authorization header wins and is never CSRF-gated (a browser cannot attach one to a
// cross-site request), so only a request actually authenticating *by cookie* has to present the
// double-submit pair.
func credentialIssuingRequestAllowed(r *http.Request) bool {
	if r.Header.Get("Authorization") != "" {
		return true
	}
	sessionCookie, err := r.Cookie(runtime.SessionCookieName)
	if err != nil || sessionCookie == nil {
		// No cookie either — the auth resolver will reject this on its own; nothing to gate here.
		return true
	}
	csrfCookie, cErr := r.Cookie(runtime.CSRFCookieName)
	csrfValue, csrfOK := "", false
	if cErr == nil && csrfCookie != nil {
		csrfValue, csrfOK = csrfCookie.Value, true
	}
	header := r.Header.Get(runtime.CSRFHeaderName)
	return runtime.CSRFMatches(csrfValue, header, csrfOK, header != "")
}
