// Cookie-based session issuance for browser callers, alongside (not instead of) the Bearer flow
// in auth.go. Two cookies set together, both Path=/: the session cookie (the JWT itself,
// HttpOnly) and the CSRF cookie (a random value, deliberately NOT HttpOnly — the double-submit
// pattern auth.go enforces on any state-changing cookie-authenticated request relies on
// same-origin JS being the only thing that *can* read it to echo it back).
package httpapi

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/hex"
	"github.com/metap-org/metap/pkg/kit/httpx"
	"github.com/metap-org/metap/pkg/kit/standard"
	"net/http"
	"strconv"
)

const sessionStartedAtCookieName = "metap_session_started_at"

// baseCookie: SameSite=Lax rather than Strict — Strict withholds the cookie even on a plain
// top-level navigation into the app from an external link, which would silently look like "not
// logged in" instead of an actual security boundary.
func baseCookie(name, value string, httpOnly, secure bool, maxAgeSeconds int) *http.Cookie {
	// False positive below (httpOnly/secure are this function's own parameters, not hardcoded
	// false — every real caller passes true for both except the CSRF cookie's deliberate
	// httpOnly=false, see this file's module doc comment; AppState.New defaults CookieSecure to
	// true, and only a plain-http dev binary opts out explicitly). Semgrep anchors a multi-line
	// match on its first line, so the suppression comment must be inline there, not above.
	return &http.Cookie{ // nosemgrep: go.lang.security.audit.net.cookie-missing-httponly.cookie-missing-httponly,go.lang.security.audit.net.cookie-missing-secure.cookie-missing-secure
		Name: name, Value: value, Path: "/", SameSite: http.SameSiteLaxMode,
		Secure: secure, HttpOnly: httpOnly, MaxAge: maxAgeSeconds,
	}
}

// sessionCookies builds the pair of Set-Cookie values a successful login issues. csrfValue is
// generated by the caller (a fresh random value per login) rather than derived from the JWT, so
// a leaked JWT alone still isn't enough to forge the CSRF header.
func sessionCookies(token, csrfValue string, ttlSeconds int, secure bool) (*http.Cookie, *http.Cookie) {
	session := baseCookie(httpx.SessionCookieName, token, true, secure, ttlSeconds)
	csrf := baseCookie(httpx.CSRFCookieName, csrfValue, false, secure, ttlSeconds)
	return session, csrf
}

// sessionStartedAtCookie is set once at login, alongside sessionCookies' pair — **never
// rewritten** after that, which is the whole mechanism: this cookie's own MaxAge equals
// absoluteMaxSeconds *as measured from the original login*, so the browser drops it on its own
// once that absolute cap elapses.
func sessionStartedAtCookie(startedAtUnixSecs, absoluteMaxSeconds int64, secure bool) *http.Cookie {
	return baseCookie(sessionStartedAtCookieName, strconv.FormatInt(startedAtUnixSecs, 10), true, secure, int(absoluteMaxSeconds))
}

// clearSessionCookies is POST /auth/logout's triple — MaxAge(-1) (immediate expiry) with every
// attribute matching what the cookie was originally set with, or the browser treats this as a
// different cookie and the original persists.
func clearSessionCookies(secure bool) (*http.Cookie, *http.Cookie, *http.Cookie) {
	session := baseCookie(httpx.SessionCookieName, "", true, secure, -1)
	csrf := baseCookie(httpx.CSRFCookieName, "", false, secure, -1)
	startedAt := baseCookie(sessionStartedAtCookieName, "", true, secure, -1)
	return session, csrf, startedAt
}

// credentialIssuingRequestAllowed: GET /auth/token's extra gate — mints a fresh Bearer JWT
// carrying the caller's full identity, a different kind of risk than the safe-method rule was
// ever about, so it is CSRF-gated despite being a GET. Mirrors auth.go's own precedence exactly:
// an Authorization header wins and is never CSRF-gated (a browser cannot attach one to a
// cross-site request), so only a request actually authenticating *by cookie* has to present the
// double-submit pair.
func credentialIssuingRequestAllowed(r *http.Request) bool {
	if r.Header.Get(standard.HeaderAuthorization) != "" {
		return true
	}
	sessionCookie, err := r.Cookie(httpx.SessionCookieName)
	if err != nil || sessionCookie == nil {
		// No cookie either — the auth resolver will reject this on its own; nothing to gate here.
		return true
	}
	csrfCookie, cErr := r.Cookie(httpx.CSRFCookieName)
	csrfValue, csrfOK := "", false
	if cErr == nil && csrfCookie != nil {
		csrfValue, csrfOK = csrfCookie.Value, true
	}
	header := r.Header.Get(httpx.CSRFHeaderName)
	return httpx.CSRFMatches(csrfValue, header, csrfOK, header != "")
}

// ssoBindCookieName binds an OIDC sign-in to the browser that started it: ssoStart sets it to a hash of
// the single-use state, and the callback accepts the state only from a browser that presents the
// same hash. Without it a callback URL obtained at the identity provider by one person could be
// opened by another browser and sign that browser in as the first person (login CSRF).
const ssoBindCookieName = "metap_sso_bind"

const ssoBindTTLSeconds = 600

func ssoBindValue(state string) string {
	sum := sha256.Sum256([]byte(state))
	return hex.EncodeToString(sum[:])
}

// ssoBindCookie is the cookie ssoStart sets (SameSite=Lax is enough: the callback is a top-level GET
// navigation, which Lax sends).
func ssoBindCookie(state string, secure bool) *http.Cookie {
	c := baseCookie(ssoBindCookieName, ssoBindValue(state), true, secure, ssoBindTTLSeconds)
	c.Path = "/auth/sso"
	return c
}

// clearSSOBindCookie removes it once the callback has used it.
func clearSSOBindCookie(secure bool) *http.Cookie {
	c := baseCookie(ssoBindCookieName, "", true, secure, -1)
	c.Path = "/auth/sso"
	return c
}

// ssoBoundToBrowser reports whether the request carries the binding cookie for state.
func ssoBoundToBrowser(r *http.Request, state string) bool {
	return boundBy(r, ssoBindCookieName, state)
}

func boundBy(r *http.Request, cookie, state string) bool {
	c, err := r.Cookie(cookie)
	return err == nil && subtle.ConstantTimeCompare([]byte(c.Value), []byte(ssoBindValue(state))) == 1
}

// samlBindCookieName is the SAML counterpart of ssoBindCookieName. It is a separate cookie because
// the identity provider answers with a cross-site POST, which a SameSite=Lax cookie does not follow.
const samlBindCookieName = "metap_saml_bind"

// samlBindCookie is SameSite=None so that POST carries it, and browsers keep such a cookie only when
// it is Secure — whatever AppState.CookieSecure says. SAML therefore needs https (or localhost, which
// browsers treat as secure).
func samlBindCookie(state string) *http.Cookie {
	c := baseCookie(samlBindCookieName, ssoBindValue(state), true, true, ssoBindTTLSeconds)
	c.Path, c.SameSite = "/auth/saml", http.SameSiteNoneMode
	return c
}

func clearSAMLBindCookie() *http.Cookie {
	c := samlBindCookie("")
	c.Value, c.MaxAge = "", -1
	return c
}

// samlBoundToBrowser reports whether the request carries the binding cookie for relayState.
func samlBoundToBrowser(r *http.Request, relayState string) bool {
	return boundBy(r, samlBindCookieName, relayState)
}
